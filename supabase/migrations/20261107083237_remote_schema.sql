CREATE OR REPLACE FUNCTION public.telegram_queue_notice()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare k text; rid bigint;
begin
  k := case tg_table_name when 'registrations' then 'player' else 'game' end;
  if k='player' then
    if new.status <> 'pending' or (tg_op='UPDATE' and old.status is not distinct from new.status) then return new; end if;
    rid := new.registration_id;
  else
    if new.deleted or new.status not in ('pending_submit','pending_edit') or
      (tg_op='UPDATE' and old.status is not distinct from new.status) then return new; end if;
    rid := new.game_id;
  end if;
  insert into public.telegram_outbox(bot,recipient,user_id,payload)
    select 'admin',telegram_id,user_id,jsonb_build_object('kind',k,'record_id',rid)
    from public.telegram_admin_links where notifications='instant';
  return new;
end $function$
;

CREATE OR REPLACE FUNCTION public.telegram_review(p_action_id text, p_telegram_id bigint, p_decision text, p_reason text, p_bootstrap boolean DEFAULT false)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare a public.telegram_admin_actions; u public.users; old_row jsonb; new_row jsonb;
  required_permission text; target_status text; r public.game_info; reg public.registrations; new_player int4;
  is_super boolean; played boolean := false;
begin
  select * into a from public.telegram_admin_actions where id = p_action_id for update;
  if a.id is null or a.telegram_id <> p_telegram_id or a.expires_at <= now() or a.consumed_at is not null then
    raise exception 'This action expired or was already handled. Refresh the queue.';
  end if;
  select * into u from public.users where id = a.user_id and status = 'active' for share;
  if u.id is null or not exists(select 1 from public.telegram_admin_links
    where user_id = a.user_id and telegram_id = p_telegram_id) then raise exception 'Admin access removed'; end if;
  required_permission := case a.kind when 'player' then 'players.manage' else 'games.manage' end;
  if not p_bootstrap and not exists(
    select 1 from public.user_roles ur join public.role_permissions rp on rp.role_id=ur.role_id
      join public.permissions pm on pm.id=rp.permission_id
    where ur.user_id=u.id and ur.valid_from<=now() and (ur.valid_until is null or ur.valid_until>now())
      and pm.name=required_permission) then raise exception 'Permission removed'; end if;
  -- Request 15: super admins hold admins.manage (bootstrap admins count as super admins).
  is_super := p_bootstrap or exists(
    select 1 from public.user_roles ur join public.role_permissions rp on rp.role_id=ur.role_id
      join public.permissions pm on pm.id=rp.permission_id
    where ur.user_id=u.id and ur.valid_from<=now() and (ur.valid_until is null or ur.valid_until>now())
      and pm.name='admins.manage');
  if p_decision not in ('approve','reject') then raise exception 'Invalid decision'; end if;
  if p_decision='reject' and (p_reason is null or length(p_reason)=0 or length(p_reason)>300) then
    raise exception 'Choose a rejection reason'; end if;
  if a.kind = 'player' then
    select * into reg from public.registrations where registration_id=a.record_id for update;
    if reg.registration_id is null or reg.status <> 'pending' then raise exception 'Registration already handled'; end if;
    old_row := to_jsonb(reg);
  else
    select * into r from public.game_info where game_id=a.record_id for update;
    perform 1 from public.game_result where game_id=a.record_id order by starting_seat for update;
    if r.game_id is null or r.deleted or r.status not in ('pending_submit','pending_edit') then
      raise exception 'Game already handled'; end if;
    -- Request 15: organisers only review games at their own venues.
    if not is_super and exists(select 1 from public.venue_organisers o where o.user_id=u.id)
      and not exists(select 1 from public.venue_organisers o where o.user_id=u.id and o.venue_id=r.venue_id) then
      raise exception 'This game is at a venue you don''t organise'; end if;
    if u.player_id is null then raise exception 'Link your admin account to your player before reviewing games'; end if;
    played := r.recorded_by_pid = u.player_id or exists(select 1 from public.game_result where game_id=r.game_id and player_id=u.player_id);
    if played and not (is_super and p_decision='approve') then
      raise exception 'Another admin must review games you played in or recorded'; end if;
    if p_decision='approve' and (select count(*) from public.game_result where game_id=r.game_id) <> 4 then
      raise exception 'Game needs four seats. Review it on the website.'; end if;
    if p_decision='approve' and ((select count(distinct player_id) from public.game_result where game_id=r.game_id) <> 4 or
      exists(select 1 from public.game_result gr left join public.player_info pi on pi.player_id=gr.player_id
        where gr.game_id=r.game_id and pi.player_id is null)) then
      raise exception 'Game needs four different registered players. Review it on the website.'; end if;
    if p_decision='approve' and not exists(select 1 from public.ruleset_info rs where rs.ruleset_id=r.ruleset_id
      and (select sum(final_score) from public.game_result where game_id=r.game_id) = rs.initial_value*4-coalesce(r.leftover_deposits,0)*10) then
      raise exception 'Score total does not match the ruleset. Review it on the website.'; end if;
    old_row := to_jsonb(r);
  end if;
  if public.telegram_review_snapshot(a.kind,a.record_id) is distinct from a.snapshot then
    raise exception 'This record changed. Refresh the queue before deciding.'; end if;
  if a.kind='player' then
    if p_decision = 'approve' then
      new_player := public.approve_registration(reg.registration_id);
      target_status := 'approved';
    else
      update public.registrations set status='rejected', status_reason=p_reason, decided_at=now()
        where registration_id=reg.registration_id;
      target_status := 'rejected';
    end if;
    select to_jsonb(x) into new_row from public.registrations x where x.registration_id=reg.registration_id;
    if reg.telegram_id is not null then
      insert into public.telegram_outbox(bot,recipient,payload,dedupe_key) values('player',reg.telegram_id,
        jsonb_build_object('text',case p_decision when 'approve' then
          'Hi '||coalesce(reg.called_name, reg.display_name)||', your SgRiichi registration is approved. Welcome! Your SgRiichi ID is '||new_player||'. You can now join recorded games.'
        else 'Hi '||coalesce(reg.called_name, reg.display_name)||', your SgRiichi registration wasn''t approved. Reason: '||p_reason||'. Reply to an admin if you think this is a mistake.' end),
        'review:'||a.id);
    end if;
  else
    target_status := case p_decision when 'approve' then 'approved' else 'rejected' end;
    update public.game_info set status=target_status::public.game_status where game_id=a.record_id
      returning to_jsonb(game_info.*) into new_row;
  end if;
  update public.telegram_admin_actions set consumed_at=now() where id=a.id;
  insert into public.audit_log(actor_user_id,action,table_name,record_id,old_values,new_values)
    values(u.id,'telegram.'||p_decision,case a.kind when 'player' then 'registrations' else 'game_info' end,
      a.record_id::text,old_row,new_row||jsonb_build_object('reason',p_reason,'telegram_id',p_telegram_id,'self_approved',played));
  return jsonb_build_object('kind',a.kind,'id',a.record_id,'status',target_status,'player_id',new_player,'self_approved',played);
end $function$
;

CREATE OR REPLACE FUNCTION public.telegram_review_snapshot(p_kind text, p_record_id bigint)
 RETURNS text
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select case p_kind
    when 'player' then (select md5(to_jsonb(r)::text) from public.registrations r where r.registration_id = p_record_id)
    when 'game' then (select md5(to_jsonb(g)::text || coalesce((select jsonb_agg(to_jsonb(r) order by r.starting_seat)::text
      from public.game_result r where r.game_id = g.game_id),'')) from public.game_info g where g.game_id = p_record_id)
  end
$function$
;

CREATE OR REPLACE FUNCTION public.telegram_schedule_digests()
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare l public.telegram_admin_links; sg timestamp := now() at time zone 'Asia/Singapore';
begin
  for l in select * from public.telegram_admin_links where notifications='daily' and next_digest_at<=now() for update skip locked loop
    if extract(hour from sg) >= l.digest_hour then
      insert into public.telegram_outbox(bot,recipient,user_id,payload,dedupe_key)
        values('admin',l.telegram_id,l.user_id,'{"kind":"digest"}', 'digest:'||l.user_id||':'||sg::date)
        on conflict(dedupe_key) do nothing;
      update public.telegram_admin_links set next_digest_at=((sg::date+1)+make_interval(hours=>l.digest_hour)) at time zone 'Asia/Singapore'
        where user_id=l.user_id;
    end if;
  end loop;
  delete from public.telegram_admin_actions where expires_at<now()-interval '7 days';
  delete from public.telegram_admin_link_tokens where expires_at<now();
  delete from public.telegram_outbox where sent_at<now()-interval '30 days';
end $function$
;

CREATE OR REPLACE FUNCTION public.block_uma_value_updates()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
    IF (OLD.uma_rank1, OLD.uma_rank2, OLD.uma_rank3, OLD.uma_rank4)
       IS DISTINCT FROM
       (NEW.uma_rank1, NEW.uma_rank2, NEW.uma_rank3, NEW.uma_rank4)
    THEN
        RAISE EXCEPTION
            'uma values are append-only: add a new row instead of editing positional_uma_id %',
            OLD.positional_uma_id;
    END IF;
    RETURN NEW;
END;
$function$
;

