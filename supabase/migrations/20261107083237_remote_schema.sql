CREATE OR REPLACE FUNCTION public.approve_registration(p_registration_id integer)
 RETURNS integer
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare r public.registrations; new_id int4;
begin
  select * into r from public.registrations where registration_id = p_registration_id for update;
  if r.registration_id is null then raise exception 'Registration not found'; end if;
  if r.status <> 'pending' then raise exception 'Registration already handled'; end if;
  perform pg_advisory_xact_lock(hashtext('public.player_info.player_id'));
  select coalesce(max(player_id), 0) + 1 into new_id from public.player_info;
  insert into public.player_info (player_id, display_name, telegram_id, status, ctry_cd, cty_cd)
    values (new_id, r.display_name, r.telegram_id, 'active', r.ctry_cd, r.cty_cd);
  insert into public.player_details (
    player_id, date_joined, full_name_nric, called_name, surname, display_name_format,
    year_of_birth_range, proficiency, consent, email, referred_by, contact_number)
  values (
    new_id, (r.created_at at time zone 'Asia/Singapore')::date, r.full_name_nric, r.called_name, r.surname,
    r.display_name_format, r.year_of_birth_range, r.proficiency, r.consent, r.email, r.referred_by, r.contact_number);
  -- Keep player_info's own counter past the ids given here.
  perform setval(pg_get_serial_sequence('public.player_info', 'player_id'), new_id);
  update public.registrations set status = 'approved', player_id = new_id, decided_at = now(), status_reason = null
    where registration_id = r.registration_id;
  return new_id;
end $function$
;

