CREATE OR REPLACE FUNCTION public.telegram_consume_link(p_hash text, p_telegram_id bigint)
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare uid bigint;
begin
  select user_id into uid from public.telegram_admin_link_tokens
    where token_hash = p_hash and expires_at > now() for update;
  if uid is null then raise exception 'Link expired or already used'; end if;
  perform pg_advisory_xact_lock(uid);
  if not exists(select 1 from public.users where id = uid and status = 'active') then
    raise exception 'Admin account is inactive';
  end if;
  if not exists(select 1 from public.users u join public.player_info p on p.player_id = u.player_id
    where u.id = uid and p.status = 'active' and p.telegram_id = p_telegram_id) then
    raise exception 'Connect from the Telegram account linked to your SgRiichi player';
  end if;
  -- Explicit disconnect in the signed-in website is required before replacing an identity.
  insert into public.telegram_admin_links(user_id, telegram_id) values(uid, p_telegram_id);
  delete from public.telegram_admin_link_tokens where user_id = uid;
  insert into public.audit_log(actor_user_id,action,table_name,record_id,new_values)
    values(uid,'telegram.link','telegram_admin_links',uid::text,jsonb_build_object('telegram_id',p_telegram_id));
  return uid;
end $function$
;

